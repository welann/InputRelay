import SwiftUI

/// 明亮的控制面板配色，弹窗和主界面共用同一组语义色。
enum AppTheme {
    static let background = Color(hex: "#F3F6FA")
    static let surface = Color.white
    static let inset = Color(hex: "#EBF0F6")
    static let selection = Color(hex: "#E1EEFF")
    static let border = Color(hex: "#CED8E5")
    static let text = Color(hex: "#172B46")
    static let secondary = Color(hex: "#52647B")
    static let muted = Color(hex: "#64748B")
    static let accent = Color(hex: "#1765CC")
    static let success = Color(hex: "#167348")
    static let warning = Color(hex: "#986000")
    static let danger = Color(hex: "#C43D3D")
    static let onAccent = Color.white
}
